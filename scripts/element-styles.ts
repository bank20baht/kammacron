/**
 * Writes `apps/web/src/elements.css`: the stylesheets of the <baht-*> elements `elements.ts`
 * and `elements-later.ts` register, and no others, in the order `@20baht/ui` says to link them. Run it after adding an
 * element there (`bun run styles`); `bun run styles:check` (in `check:fast`) fails when the file
 * is behind.
 */
import { readFile, writeFile } from 'node:fs/promises'
import { join } from 'node:path'

const web = join(import.meta.dir, '..', 'apps', 'web')
const target = join(web, 'src', 'elements.css')

type Index = { order: string[]; elements: Record<string, string[]> }

const index = (await Bun.file(
  Bun.resolveSync('@20baht/ui/css/components/index.json', web),
).json()) as Index

// both files register on every page; they differ only in when their code arrives
const sources = await Promise.all(
  ['elements.ts', 'elements-later.ts'].map((name) => readFile(join(web, 'src', name), 'utf8')),
)
const registered = [
  ...sources.join('\n').matchAll(/^import '@20baht\/ui\/components\/([\w-]+)'/gm),
].flatMap((match) => match[1] ?? [])

const unknown = registered.filter((name) => !(name in index.elements))
if (unknown.length > 0)
  throw new Error(`@20baht/ui has no stylesheet list for: ${unknown.join(', ')}`)

const needed = new Set(['base', ...registered.flatMap((name) => index.elements[name] ?? [])])
const sheets = index.order.filter((name) => needed.has(name))

const css = [
  '/*',
  ' * Generated by scripts/element-styles.ts from src/elements.ts: `bun run styles`. Do not edit.',
  ' * The styles of the elements this app registers, in the order @20baht/ui links them.',
  ' */',
  "@import '@20baht/ui/css/tokens.css';",
  ...sheets.map((name) => `@import '@20baht/ui/css/components/${name}.css';`),
  '',
].join('\n')

if (process.argv.includes('--check')) {
  const current = await readFile(target, 'utf8').catch(() => '')
  if (current !== css) {
    console.error('apps/web/src/elements.css is behind src/elements.ts: run `bun run styles`')
    process.exit(1)
  }
} else {
  await writeFile(target, css)
  console.log(`elements.css: ${String(sheets.length)} of ${String(index.order.length)} sheets`)
}
