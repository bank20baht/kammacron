/**
 * Writes `apps/web/src/elements.css`: the stylesheets of the <baht-*> elements the app registers
 * (the shell's in `elements.ts`, a page's in its own component), and no others, in the order
 * `@20baht/ui` says to link them. Run it after a component imports a new element
 * (`bun run styles`); `bun run styles:check` (in `check:fast`) fails when the file
 * is behind.
 */
import { readFile, writeFile } from 'node:fs/promises'
import { join } from 'node:path'

const web = join(import.meta.dir, '..', 'apps', 'web')
const target = join(web, 'src', 'elements.css')

type Index = { order: string[]; elements: Record<string, string[]> }

const index = (await Bun.file(
  Bun.resolveSync('@20baht/ui/css/components/index.json', web),
).json()) as Index

// the shell's elements (elements.ts) and those each component imports for its own template:
// one stylesheet for the app, so every file under src/ that registers an element counts
const sources = await Promise.all(
  (await Array.fromAsync(new Bun.Glob('**/*.ts').scan({ cwd: join(web, 'src') })))
    .filter((name) => !name.endsWith('.spec.ts'))
    .sort()
    .map((name) => readFile(join(web, 'src', name), 'utf8')),
)
const registered = [
  ...new Set(
    // a side-effect import, or a value taken from the element's module (`calendarRange`)
    [
      ...sources.join('\n').matchAll(/(?:import|from) '@20baht\/ui\/components\/([\w-]+)'/g),
    ].flatMap((match) => match[1] ?? []),
  ),
]

const unknown = registered.filter((name) => !(name in index.elements))
if (unknown.length > 0)
  throw new Error(`@20baht/ui has no stylesheet list for: ${unknown.join(', ')}`)

const needed = new Set(['base', ...registered.flatMap((name) => index.elements[name] ?? [])])
const sheets = index.order.filter((name) => needed.has(name))

const css = [
  '/*',
  ' * Generated by scripts/element-styles.ts from the elements src/ imports: `bun run styles`. Do not edit.',
  ' * The styles of the elements this app registers, in the order @20baht/ui links them.',
  ' */',
  "@import '@20baht/ui/css/tokens.css';",
  ...sheets.map((name) => `@import '@20baht/ui/css/components/${name}.css';`),
  '',
].join('\n')

if (process.argv.includes('--check')) {
  const current = await readFile(target, 'utf8').catch(() => '')
  if (current !== css) {
    console.error(
      'apps/web/src/elements.css is behind the elements src/ imports: run `bun run styles`',
    )
    process.exit(1)
  }
} else {
  await writeFile(target, css)
  console.log(`elements.css: ${String(sheets.length)} of ${String(index.order.length)} sheets`)
}
